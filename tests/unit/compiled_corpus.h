/**
 * @file compiled_corpus.h
 * @brief Test data: functions compiled by gcc, as machine-code bytes.
 *
 * The lifter and the SSA constructor are mostly tested on hand-assembled code, where every
 * instruction is chosen to make one point. This is the other kind of input -- what a compiler
 * actually emits, shapes nobody chose -- and it found a bug the hand-written inputs never did
 * (an SSA constructor that left register reads unresolved at the end of a loop header).
 *
 * SOURCE (compiled_corpus.c, kept here so the bytes can be regenerated):
 *
 *   long sum_to(long n) { long s = 0; for (long i = 0; i < n; i++) s += i; return s; }
 *
 *   long collatz_steps(long n) {
 *       long steps = 0;
 *       while (n != 1 && steps < 1000) {
 *           if (n & 1) n = 3 * n + 1; else n = n >> 1;
 *           steps++;
 *       }
 *       return steps;
 *   }
 *
 *   long nested(long a, long b) {
 *       long t = 0;
 *       for (long i = 0; i < a; i++)
 *           for (long j = 0; j < b; j++)
 *               t += i * j;
 *       return t;
 *   }
 *
 *   long clamp(long x, long lo, long hi) {
 *       if (x < lo) return lo;
 *       if (x > hi) return hi;
 *       return x;
 *   }
 *
 *   long gcd(long a, long b) {
 *       while (b != 0) { long t = a % b; a = b; b = t; }
 *       return a;
 *   }
 *
 *   long find_first(const long *p, long n, long key) {
 *       for (long i = 0; i < n; i++) {
 *           if (p[i] == key) return i;
 *           if (p[i] > key * 4) break;
 *       }
 *       return -1;
 *   }
 *
 *   long sw(long x) {
 *       switch (x) {
 *           case 0: return 11;
 *           case 1: return 22;
 *           case 2: return 5 * x;
 *           case 3: return x + 100;
 *           default: return x ^ 0x55;
 *       }
 *   }
 *
 *   long parity_sum(long n) {
 *       long e = 0, o = 0;
 *       for (long i = 0; i < n; i++) {
 *           if (i & 1) { o += i; continue; }
 *           e += i;
 *           if (e > 100000) break;
 *       }
 *       return e - o;
 *   }
 *
 * BUILD     gcc <opt> -ffreestanding -fno-pic -fcf-protection=none \
 *               -fno-asynchronous-unwind-tables -fno-stack-protector -c compiled_corpus.c
 *           for <opt> in -O0 -O1 -O2 -O3 -Os
 * EXTRACT   objcopy -O binary --only-section=.text, then each function is cut out at the
 *           address and size that `nm -S` reports for it.
 * TOOLCHAIN gcc 13.3.0, binutils 2.42 (Ubuntu 24.04). These bytes are fixed data: the tests
 *           do not recompile, so another compiler changes nothing here.
 *
 * A function whose bytes are the same at several optimisation levels is listed once, with all
 * of them in its name. Each entry is meant to be lifted with its first byte as the entry point.
 *
 * WHAT THE LIFTER MAKES OF IT is not the point of this data: 32-bit register operands are not
 * modelled (see cir_lifter_internal.h) and some instructions have no CIR effect yet. Tests use
 * these functions to check that what the lifter and SSA constructor produce is WELL FORMED, and
 * that the analyses accept it -- not that it computes what the C source does.
 */
